/** Названия из базы, которых нет среди своих записей тренера */
export function catalogNames(exclude: string[] = []): string[] {
  const ex = new Set(exclude.map((s) => s.trim().toLowerCase()))
  return EXERCISE_CATALOG.map((e) => e.name).filter((n) => !ex.has(n.toLowerCase()))
}
